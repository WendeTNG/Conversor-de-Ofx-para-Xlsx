"""IMPORTAÇÃO"""

from google.colab import files
import pandas as pd
import io
import re

"""UPLOAD"""

print("Selecione o arquivo OFX")

uploaded = files.upload()
arquivo = list(uploaded.keys())[0]
print("Arquivo", arquivo)

"""LEITURA DE ARQUIVO"""

with open(arquivo,"rb") as f:
  dados = f.read()

"""DETECTOR DE CODIFICAÇÃO AUTONOMO"""

codificacoes = [
    "utf-8",
    "cp1252",
    "latin1",
    "iso-8859-1"
]

texto = None

for cod in codificacoes:
  try:
    texto = dados. decode(cod)
    print(f"Codificação localizada: {cod}")
    break

  except UnicodeDecodeError:
    pass

#Verificar conteudo:
print(texto[:500])

"""EXTRAIR TRANSAÇÕES"""

transacoes = re.findall(
 r"<STMTTRN>(.*?)</STMTTRN>",
    texto,
    re.DOTALL
)

print("Quantidade de transações:", len(transacoes))

print(transacoes[0])

print(transacoes[1])

#EXTRAIR TODAS AS INFORMAÇÕES


def extrair_transacoes(transacoes):

  dados = []

  for t in transacoes:
    registro = {}
    linhas = t.splitlines()

    for linha in linhas:
      linha = linha.strip()
      if linha.startswith("<") and ">" in linha:

        chave, valor = linha[1:].split(">",1)

        valor = valor.split("</")[0].strip()

        registro[chave.upper()] = valor
    dados.append(registro)

  print(f"Registros extraídos: {len(dados)}")
  return pd.DataFrame(dados)

"""CRIAR DataFrame"""

df = extrair_transacoes(transacoes)
print(df.shape)
print(df.head())

print(df.columns.tolist())

"""TRATAMENTO DE DADOS"""

df["TRNAMT"] = (
    df["TRNAMT"]
    .astype(str)
    .str.replace(",",".", regex=False)
)

df["TRNAMT"] = pd.to_numeric(df["TRNAMT"], errors="coerce")

df["DTPOSTED"] = df["DTPOSTED"].str[:8]

df["DTPOSTED"] = pd.to_datetime(
    df["DTPOSTED"],
    format="%Y%m%d",
    errors="coerce"
)

df["DTPOSTED"] = df["DTPOSTED"].dt.strftime("%d/%m/%Y")

if "MEMO" not in df.columns and "NAME" in df.columns:
    df["MEMO"] = df["NAME"]

if "MEMO" not in df.columns and "PAYEE" in df.columns:
    df["MEMO"] = df["PAYEE"]


df.rename(columns={
    "TRNTYPE": "Tipo",
    "DTPOSTED": "Data",
    "TRNAMT": "Valor",
    "FITID": "Identificador",
    "CHECKNUM": "Documento",
    "MEMO": "Descrição"
}, inplace=True)

print(df.head())

"""EXPORTAÇÃO"""

from google.colab import files
nome_arquivo = "Extrato_Convertido.xlsx"
df.to_excel(nome_arquivo, index=False)
print(f"Arquivo {nome_arquivo} criado com sucesso!")

files.download(nome_arquivo)

